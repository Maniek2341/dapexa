def view_permissions(*url_names):
    """Return safe custom permissions associated with named application views."""
    missing_descriptions = set(url_names) - VIEW_PERMISSION_DESCRIPTIONS.keys()
    if missing_descriptions:
        missing = ", ".join(sorted(missing_descriptions))
        raise ValueError(f"Brak opisów uprawnień dla widoków: {missing}")

    return [
        (f"access_{name}", VIEW_PERMISSION_DESCRIPTIONS[name])
        for name in url_names
    ]
